nc <- readRDS("data/processed/seqtab_nochim.rds")
taxa <- readRDS("data/processed/taxa.rds")
md <- read.delim("data/processed/digester_metadata.tsv")
stopifnot(identical(colnames(nc), rownames(taxa)))
stopifnot(identical(rownames(nc), md$sample))
g <- unname(taxa[, "Genus"])
g[is.na(g)] <- "no_genus"
gt <- t(rowsum(t(nc), group=g))
pct <- 100 * (1 - sum(gt[, "no_genus"]) / sum(gt))
cat("Reads with a genus name:", round(pct, 1), "%\n")
prev <- colSums(gt > 0)
keep <- setdiff(names(prev)[prev >= 5], "no_genus")
cat("Named genera in >= 5 samples:", length(keep), "\n")
lg <- log(gt + 0.5)
clr <- lg - rowMeans(lg)
rel <- 100 * gt / rowSums(gt)
ca <- md$group == "cattle"
sw <- md$group == "swine"
res <- data.frame(genus=keep, prevalence=unname(prev[keep]))
res$mean_pct_cattle <- unname(colMeans(rel[ca, keep]))
res$mean_pct_swine <- unname(colMeans(rel[sw, keep]))
dif <- sapply(keep, function(k) median(clr[sw, k]) - median(clr[ca, k]))
res$clr_diff_swine_minus_cattle <- unname(dif)
pv <- sapply(keep, function(k) wilcox.test(clr[, k] ~ md$group, exact=FALSE)$p.value)
res$p <- unname(pv)
res$q <- p.adjust(res$p, method="BH")
res <- res[order(res$p), ]
write.table(res, "results/14_diffabund.tsv", sep="\t", quote=FALSE, row.names=FALSE)
cat("Genera with q < 0.05:", sum(res$q < 0.05), "\n")
cat("Genera with q < 0.10:", sum(res$q < 0.10), "\n")
print(head(res, 15), digits=3, row.names=FALSE)
