library(vegan)
set.seed(1)
nc <- readRDS("data/processed/seqtab_nochim.rds")
md <- read.delim("data/processed/digester_metadata.tsv")
stopifnot(identical(rownames(nc), md$sample))
d <- vegdist(nc / rowSums(nc), method="bray")
dm_all <- as.matrix(d)
f <- function(a, i) paste0("R2=", round(a$R2[i], 3), " p=", a$"Pr(>F)"[i])
run <- function(keep, label) {
  dm <- as.dist(dm_all[keep, keep])
  dat <- md[keep, ]
  cat("\n=====", label, "- n =", sum(keep), "=====\n")
  print(table(dat$group))
  a1 <- adonis2(dm ~ group, data=dat, permutations=9999)
  a2 <- adonis2(dm ~ fa, data=dat, permutations=9999)
  a3 <- adonis2(dm ~ group + fa, data=dat, permutations=9999, by="margin")
  cat("Group alone:", f(a1, 1), "F =", round(a1$F[1], 2), "\n")
  cat("FA alone:", f(a2, 1), "\n")
  cat("Group given FA:", f(a3, 1), "\n")
  cat("FA given group:", f(a3, 2), "\n")
  bd <- betadisper(dm, dat$group)
  pt <- permutest(bd, permutations=9999)
  cat("Mean distance to group centre:\n")
  print(round(tapply(bd$distances, dat$group, mean), 3))
  cat("Dispersion test p =", pt$tab[1, "Pr(>F)"], "\n")
}
run(rep(TRUE, nrow(md)), "ALL SAMPLES")
run(!(md$sample %in% c("s12", "c7")), "WITHOUT s12 AND c7")
