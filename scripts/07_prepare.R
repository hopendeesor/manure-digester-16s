nc <- readRDS("data/processed/seqtab_nochim.rds")
taxa <- readRDS("data/processed/taxa.rds")
stopifnot(identical(rownames(taxa), colnames(nc)))
g <- ifelse(substr(rownames(nc), 1, 1) == "c", "cattle", "swine")
meta <- data.frame(sample=rownames(nc), group=g)
write.table(meta, "data/processed/metadata.tsv", sep="\t", quote=FALSE, row.names=FALSE)
mg <- c("Methanothrix","Methanosarcina","Methanimicrococcus","Methanobrevibacter")
mg <- c(mg, "Methanobacterium","Methanosphaera","Methanospirillum")
mg <- c(mg, "Methanocorpusculum","Methanoregula","Methanoculleus")
mg <- c(mg, "Methanomassiliicoccus","Candidatus Methanoplasma","RumEn M2")
mg <- c(mg, "Candidatus Methanogranum","Candidatus Methanomethylicus")
mg <- c(mg, "Candidatus Methanofastidiosum")
isA <- which(taxa[, "Kingdom"] == "Archaea")
isM <- which(taxa[, "Genus"] %in% mg)
tot <- rowSums(nc)
out <- data.frame(group=g, reads=tot)
out$archaea_pct <- round(100 * rowSums(nc[, isA, drop=FALSE]) / tot, 2)
out$methanogen_pct <- round(100 * rowSums(nc[, isM, drop=FALSE]) / tot, 2)
write.table(out, "results/07_archaea_summary.tsv", sep="\t", quote=FALSE, col.names=NA)
cat("methanogen ASVs:", length(isM), "\n")
print(out)
