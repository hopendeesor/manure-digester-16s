library(dada2)
fl <- sort(list.files("data/processed/filtered", full.names=TRUE))
rl <- read.delim("data/processed/runlist.tsv")
ids <- sub(".fastq.gz", "", basename(fl))
names(fl) <- rl$sample_alias[match(ids, rl$run_accession)]
err <- learnErrors(fl, multithread=FALSE)
dd <- dada(fl, err=err, multithread=FALSE)
st <- makeSequenceTable(dd)
nc <- removeBimeraDenovo(st, method="consensus")
saveRDS(nc, "data/processed/seqtab_nochim.rds")
gn <- function(x) sum(getUniques(x))
tr <- cbind(denoised=sapply(dd, gn), nonchim=rowSums(nc))
write.table(tr, "results/04_track.tsv", sep="\t", quote=FALSE, col.names=NA)
cat("ASVs before chimera removal:", ncol(st), "\n")
cat("ASVs after chimera removal:", ncol(nc), "\n")
print(tr)
